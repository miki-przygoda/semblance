"""Export flyvis's trained parameters into forms the Rust side can use.

Two outputs, deliberately different in kind:

  crates/flyvis/src/pretrained.rs   model 000 only, as compile-time constants.
                                    0.3.0 validates the port against this, so it
                                    must not be able to drift or go missing.

  data/flyvis-pretrained/ensemble.csv   all 50 models, as data. Only 0.5.0 needs
                                    this, and only if the codec goes learned.

The parameters are POSITIONAL -- nodes_bias[i] means "cell type i in flyvis's
ordering". Both outputs therefore carry the orderings explicitly. Deriving them
independently and hoping they match would attach every parameter to the wrong
cell type, silently.
"""

import datetime
import pathlib
import sys

import numpy as np
import torch

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "data" / "flyvis-pretrained" / "results" / "flow" / "0000"
RS_OUT = ROOT / "crates" / "flyvis" / "src" / "pretrained.rs"
CSV_OUT = ROOT / "data" / "flyvis-pretrained" / "ensemble.csv"

VALIDATION_MODEL = "000"  # flyvis ranks its ensemble by validation loss; 000 is best


def f32(x) -> str:
    """Shortest string that round-trips as f32, so Rust reads back identical bits.

    numpy 2 renders scalars as `np.float32(0.5)`, which is not a Rust literal, so
    this formats from a plain float and widens precision until the value survives
    a round-trip through f32.
    """
    v = np.float32(x)
    s = repr(float(v))
    for prec in range(1, 10):
        cand = f"{float(v):.{prec}g}"
        if np.float32(float(cand)) == v:
            s = cand
            break
    # `%g` renders 0.0 as "0" and -1.0 as "-1", which are integer literals in
    # Rust and will not coerce into an [f32; N].
    if not any(c in s for c in ".eE"):
        s += ".0"
    return s


def orderings():
    from flyvis.connectome import ConnectomeFromAvgFilters

    c = ConnectomeFromAvgFilters()
    dec = lambda a: [x.decode() if isinstance(x, (bytes, np.bytes_)) else str(x) for x in a]

    cell_types, seen = [], set()
    for t in dec(c.nodes.type[:]):
        if t not in seen:
            seen.add(t)
            cell_types.append(t)

    conn_types, seen = [], set()
    for a, b in zip(dec(c.edges.source_type[:]), dec(c.edges.target_type[:])):
        if (a, b) not in seen:
            seen.add((a, b))
            conn_types.append((a, b))

    return cell_types, conn_types, len(c.nodes.type[:]), len(c.edges.source_type[:])


def main() -> int:
    models = sorted(d for d in RESULTS.iterdir() if d.is_dir() and d.name.isdigit())
    print(f"  models: {len(models)}")

    cell_types, conn_types, n_nodes, n_edges = orderings()
    print(f"  ordering: {len(cell_types)} cell types, {len(conn_types)} connection types")
    print(f"  flyvis built: {n_nodes} neurons, {n_edges} synapses")

    ck = lambda d: torch.load(d / "best_chkpt", map_location="cpu", weights_only=False)["network"]
    ref = ck(RESULTS / VALIDATION_MODEL)
    assert len(cell_types) == ref["nodes_bias"].numel() == 65
    assert len(conn_types) == ref["edges_syn_strength"].numel() == 604

    import flyvis
    stamp = (f"flyvis {getattr(flyvis, '__version__', '?')} · model {VALIDATION_MODEL} "
             f"(best of {len(models)} by validation loss) · exported "
             f"{datetime.date.today().isoformat()}")

    # ---- Rust constants: the single validation model -----------------------
    w = []
    w.append("//! flyvis's trained parameters for the validation model.")
    w.append("//!")
    w.append("//! GENERATED by `tools/export_params.py`. Do not edit by hand.")
    w.append(f"//! {stamp}")
    w.append("//!")
    w.append("//! These are POSITIONAL. `BIAS[i]` belongs to `CELL_TYPES[i]`, and")
    w.append("//! `SYN_STRENGTH[j]` to `CONN_TYPES[j]`. The orderings are flyvis's own,")
    w.append("//! taken from its built connectome -- do not re-derive them.")
    w.append("//!")
    w.append(f"//! flyvis's build yields {n_nodes} neurons and {n_edges} synapses;")
    w.append("//! `SYN_COUNT` is included so an independent expansion can be checked")
    w.append("//! against it rather than trusted -- but note it is stored as")
    w.append("//! **ln(count)**, matching flyvis's lognormal parameterisation. A check")
    w.append("//! against integer synapse counts must `exp()` first.")
    w.append("")
    w.append("// Clippy's `approx_constant` lint is deny-by-default and fires on this")
    w.append("// data: ln(2) = 0.6931472 and ln(10) = 2.3025851 genuinely occur in")
    w.append("// SYN_COUNT, because it is log-space. They are measurements, not")
    w.append("// hand-written approximations of std constants.")
    w.append("#![allow(clippy::approx_constant)]")
    w.append("")
    w.append(f"/// Cell types, in flyvis's node ordering. {len(cell_types)} entries.")
    w.append(f"pub static CELL_TYPES: [&str; {len(cell_types)}] = [")
    for t in cell_types:
        w.append(f'    "{t}",')
    w.append("];")
    w.append("")
    w.append(f"/// Connection types as (source, target), in flyvis's edge ordering. {len(conn_types)} entries.")
    w.append(f"pub static CONN_TYPES: [(&str, &str); {len(conn_types)}] = [")
    for a, b in conn_types:
        w.append(f'    ("{a}", "{b}"),')
    w.append("];")
    w.append("")

    for const, key, doc in [
        ("BIAS", "nodes_bias", "Trained resting potential per cell type."),
        ("TIME_CONST", "nodes_time_const", "Trained membrane time constant per cell type."),
        ("SYN_STRENGTH", "edges_syn_strength", "Trained unitary synapse scaling per connection type."),
        ("SIGN", "edges_sign", "Synapse sign per connection type. Fixed from the connectome, not trained."),
        ("SYN_COUNT", "edges_syn_count", "Synapse counts as **ln(count)**. Fixed from the connectome, not trained."),
    ]:
        v = ref[key].numpy()
        w.append(f"/// {doc}")
        w.append(f"pub static {const}: [f32; {v.size}] = [")
        for i in range(0, v.size, 8):
            w.append("    " + " ".join(f32(x) + "," for x in v[i:i + 8]))
        w.append("];")
        w.append("")

    w.append("/// The free parameters, as flyvis counts them:")
    w.append(f"/// {len(cell_types)} biases + {len(cell_types)} time constants + "
             f"{len(conn_types)} synapse strengths.")
    w.append(f"pub const FREE_PARAMETER_COUNT: usize = {len(cell_types)*2 + len(conn_types)};")
    RS_OUT.write_text("\n".join(w) + "\n")
    print(f"  wrote {RS_OUT.relative_to(ROOT)}  ({len(w)} lines)")

    # ---- CSV: the whole ensemble -------------------------------------------
    rows = ["# flyvis trained ensemble. " + stamp.replace(f"model {VALIDATION_MODEL} (best of 50 by validation loss) · ", ""),
            "# Positional: index refers to the ordering in crates/flyvis/src/pretrained.rs.",
            "# kind is one of bias|time_const|syn_strength. name is the cell type or 'src>tar'.",
            "model,kind,index,name,value"]
    for d in models:
        net = ck(d)
        for kind, key, names in [
            ("bias", "nodes_bias", cell_types),
            ("time_const", "nodes_time_const", cell_types),
            ("syn_strength", "edges_syn_strength", [f"{a}>{b}" for a, b in conn_types]),
        ]:
            v = net[key].numpy()
            for i, x in enumerate(v):
                rows.append(f"{d.name},{kind},{i},{names[i]},{f32(x)}")
    CSV_OUT.write_text("\n".join(rows) + "\n")
    print(f"  wrote {CSV_OUT.relative_to(ROOT)}  ({len(rows) - 4} data rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
